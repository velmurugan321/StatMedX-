import { useCallback, useEffect, useRef, useState } from "react";
import { api, downloadFile } from "../api";
import { useApp } from "../state";
import ResultsView from "../components/ResultsView";
import { Btn, ErrorNote, Spinner } from "../components/ui";
import { getOfflineResult, listOfflineResults } from "../offline";
import * as XLSX from "xlsx";

export default function Results() {
  const { activeDataset } = useApp();
  const [list, setList] = useState<any[]>([]);
  const [selected, setSelected] = useState<any | null>(null);
  const [loading, setLoading] = useState(true);
  const [err, setErr] = useState<string | null>(null);
  const reportContent = useRef<HTMLDivElement>(null);

  const loadList = useCallback(async () => {
    setLoading(true);
    try {
      if (activeDataset?.id < 0) {
        const local = await listOfflineResults(activeDataset.id);
        setList(local);
        setSelected(current => local.find(item => item.id === current?.id) ?? null);
        return;
      }
      const q = activeDataset ? `?dataset_id=${activeDataset.id}` : "";
      const l = await api<any[]>(`/api/results${q}`);
      const safeList = Array.isArray(l) ? l : [];
      setList(safeList);
      if (!safeList.some((item: any) => item.id === selected?.id)) setSelected(null);
    } catch {
      const local = await listOfflineResults(activeDataset?.id);
      setList(local);
      setSelected(current => local.find(item => item.id === current?.id) ?? null);
    } finally {
      setLoading(false);
    }
  }, [activeDataset?.id, selected?.id]);

  useEffect(() => {
    loadList();
  }, [loadList]);

  const openResult = async (id: number) => {
    setErr(null);
    if (id < 0) {
      setSelected(await getOfflineResult(id));
      return;
    }
    const r = await api<any>(`/api/results/${id}`);
    setSelected(r);
  };

  const printReport = () => {
    if (!selected) return;
    const w = window.open("", "_blank");
    if (!w) { setErr("Allow pop-ups to create the PDF report."); return; }
    const entities: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
    const escapeHtml = (value: unknown) => String(value ?? "").replace(/[&<>"']/g, char => entities[char]);
    const title = escapeHtml(selected.title || selected.result?.title || "Analysis results");
    const datasetName = escapeHtml(activeDataset?.name || "Dataset");
    const created = escapeHtml(selected.created_at ? new Date(selected.created_at).toLocaleString() : new Date().toLocaleString());
    const content = reportContent.current?.innerHTML || "<p>No printable result content.</p>";
    w.document.open();
    w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${title} — StatMedX</title><style>
      @page{size:auto;margin:18mm}body{font:12px/1.5 Arial,sans-serif;color:#172033;margin:0}h1{font-size:22px;margin:0 0 4px}h2,h3{break-after:avoid}header{border-bottom:2px solid #0284c7;padding-bottom:12px;margin-bottom:18px}.meta{color:#64748b;font-size:11px}table{border-collapse:collapse;width:100%;margin:10px 0 16px;break-inside:auto}thead{display:table-header-group}tr{break-inside:avoid;break-after:auto}th,td{border:1px solid #cbd5e1;padding:6px 8px;text-align:left;vertical-align:top}th{background:#f1f5f9}pre,code{white-space:pre-wrap;overflow-wrap:anywhere}.result-block{break-inside:avoid;margin:12px 0}svg{max-width:100%;height:auto}img{max-width:100%}.footer{border-top:1px solid #cbd5e1;margin-top:24px;padding-top:8px;color:#64748b;font-size:10px}@media print{a{color:inherit;text-decoration:none}}
    </style></head><body><header><h1>${title}</h1><div class="meta">StatMedX · Dataset: ${datasetName} · Generated: ${created}</div></header><main>${content}</main><div class="footer">Generated by StatMedX</div><script>window.onload=()=>setTimeout(()=>window.print(),250)</script></body></html>`);
    w.document.close();
  };

  const exportOffline = (format: "csv" | "excel") => {
    if (!selected || selected.id >= 0) return;
    const rows: any[][] = [];
    for (const b of (Array.isArray(selected.result?.blocks) ? selected.result.blocks : [])) {
      if (b.type === "table") {
        rows.push([b.name || "Results"]);
        rows.push((Array.isArray(b.columns) ? b.columns : []).map((c: any) => c?.label ?? c?.key ?? ""));
        rows.push(...(Array.isArray(b.rows) ? b.rows : [])); rows.push([]);
      } else if (b.type === "text") rows.push([String(b.content || "").replace(/<[^>]+>/g, "")]);
    }
    let blob: Blob;
    if (format === "excel") {
      const wb = XLSX.utils.book_new(); XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows.length ? rows : [[selected.title]]), "Results");
      blob = new Blob([XLSX.write(wb, { bookType: "xlsx", type: "array" })], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
    } else {
      const esc = (v: any) => { const s = v == null ? "" : String(v); return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
      blob = new Blob(["\uFEFF", rows.map(r => r.map(esc).join(",")).join("\r\n")], { type: "text/csv;charset=utf-8" });
    }
    const a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = `${selected.module}-results.${format === "excel" ? "xlsx" : "csv"}`; a.click(); setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  };

  const copyTables = async () => {
    if (!selected) return;
    const lines: string[] = [];
    for (const b of (Array.isArray(selected?.result?.blocks) ? selected.result.blocks : [])) {
      if (b.type === "table") {
        lines.push(b.name || "");
        const columns = Array.isArray(b.columns) ? b.columns : [];
        const rows = Array.isArray(b.rows) ? b.rows : [];
        lines.push(columns.map((c: any) => c?.label ?? c?.key ?? "").join("\t"));
        for (const r of rows) lines.push((Array.isArray(r) ? r : []).map((v: any) => (v == null ? "" : String(v))).join("\t"));
        lines.push("");
      } else if (b.type === "text") {
        lines.push(b.content.replace(/<[^>]+>/g, ""));
        lines.push("");
      }
    }
    await navigator.clipboard.writeText(lines.join("\n"));
  };

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <h1 className="text-xl font-extrabold tracking-tight text-slate-900">Results window</h1>
          <p className="text-[13px] text-slate-500">
            Every saved analysis {activeDataset ? `for ${activeDataset.name}` : "(all datasets)"}.
          </p>
        </div>
        {selected && (
          <div className="flex flex-wrap gap-1.5">
            <Btn variant="ghost" onClick={() => setSelected(null)}>← Back to results list</Btn>
            <Btn variant="ghost" onClick={() => copyTables().catch((e: any) => setErr(e?.message || "Could not copy result."))}>⧉ Copy</Btn>
            {selected.id < 0 ? <>
              <Btn variant="ghost" onClick={() => { try { exportOffline("excel"); } catch (e: any) { setErr(e?.message || "Excel export failed."); } }}>⬇ Excel</Btn>
              <Btn variant="ghost" onClick={() => { try { exportOffline("csv"); } catch (e: any) { setErr(e?.message || "CSV export failed."); } }}>⬇ CSV</Btn>
              <Btn variant="ghost" onClick={printReport}>⬇ PDF / Print</Btn>
            </> : <>
              <Btn variant="ghost" onClick={() => downloadFile(`/api/results/${selected.id}/export?format=excel`, `${selected.module}-results.xlsx`).catch((e: any) => setErr(e.message))}>⬇ Excel</Btn>
              <Btn variant="ghost" onClick={() => downloadFile(`/api/results/${selected.id}/export?format=csv`, `${selected.module}-results.csv`).catch((e: any) => setErr(e.message))}>⬇ CSV</Btn>
              <Btn variant="ghost" onClick={() => downloadFile(`/api/results/${selected.id}/export?format=docx`, `${selected.module}-results.docx`).catch((e: any) => setErr(e.message))}>⬇ Word</Btn>
              <Btn variant="ghost" onClick={printReport}>⬇ PDF / Print</Btn>
            </>}
          </div>
        )}
      </div>

      <ErrorNote msg={err} />

      <div className="grid gap-4 lg:grid-cols-[300px_1fr]">
        <div className="h-fit space-y-1.5 rounded-2xl border border-slate-200 bg-white p-2">
          {loading && <Spinner label="Loading results…" />}
          {!loading && list.length === 0 && (
            <div className="p-6 text-center text-[13px] text-slate-400">No saved results yet — run an analysis.</div>
          )}
          {(Array.isArray(list) ? list : []).map((r) => (
            <button key={r.id}
                    className={`w-full rounded-lg px-3 py-2 text-left transition ${
                      selected?.id === r.id ? "bg-sky-50 ring-1 ring-sky-200" : "hover:bg-slate-50"
                    }`}
                    onClick={() => openResult(r.id).catch((e: any) => setErr(e?.message || "Could not open result."))}>
              <div className="truncate text-[13px] font-semibold text-slate-700">{r.title}</div>
              <div className="text-[11px] text-slate-400">
                {r.module} · {new Date(r.created_at).toLocaleString()}
              </div>
            </button>
          ))}
        </div>
        <div className="min-w-0">
          {selected ? (
            <div ref={reportContent}><ResultsView result={selected.result} /></div>
          ) : (
            !loading && (
              <div className="rounded-2xl border-2 border-dashed border-slate-200 p-12 text-center text-sm text-slate-400">
                Select a saved result to view it.
              </div>
            )
          )}
        </div>
      </div>
    </div>
  );
}

